if __name__ == "__main__":
    import sys

    logging.basicConfig(level=logging.INFO, format="%(levelname)s: %(message)s")

    # Default to the standard dummy-CV directory
    BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    cv_dir = os.path.join(BASE_DIR, "mysite", "static", "uploads", "customers", "cv")

    if not os.path.isdir(cv_dir):
        print(f"CV directory not found: {cv_dir}")
        sys.exit(1)

    for fname in sorted(os.listdir(cv_dir)):
        if fname.lower().endswith(".pdf"):
            full_path = os.path.join(cv_dir, fname)
            print(f"\n=== Parsing: {fname} ===")
            try:
                data = parse_cv(full_path)
                for key, value in data.items():
                    if key != "raw_text":
                        print(f"  {key}: {value}")
            except Exception as err:
                print(f"  ERROR: {err}")
